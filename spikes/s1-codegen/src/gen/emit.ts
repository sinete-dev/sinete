// IR -> one TS module per document: exported TS types (zero runtime) + descriptor consts (runtime),
// sharing the same identifier so `serialize(TNFe, value)` infers the value type.
import type { AttrIR, ComplexIR, ParticleIR, SchemaIR, SimpleIR, TypeRef } from "./ir.ts";

const ident = (id: string) => id.replace(/[^A-Za-z0-9_$]/g, "_");
const lit = (s: string) => JSON.stringify(s);
const propKey = (s: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s) ? s : lit(s));

function jsdoc(lines: (string | undefined)[], indent: string): string {
  const ls = lines.filter(Boolean).flatMap((l) => l!.replace(/\*\//g, "*\\/").split("\n")).map((l) => l.trim()).filter(Boolean);
  if (!ls.length) return "";
  if (ls.length === 1) return `${indent}/** ${ls[0]} */\n`;
  return `${indent}/**\n${ls.map((l) => `${indent} * ${l}`).join("\n")}\n${indent} */\n`;
}

function facetSummary(s: SimpleIR): string | undefined {
  const f = s.facets;
  const parts: string[] = [];
  if (s.name) parts.push(`xsd:${s.name}`);
  else if (s.chain.length) parts.push(`xsd:${s.chain[0]}`);
  if (f.length !== undefined) parts.push(`length ${f.length}`);
  if (f.minLength !== undefined || f.maxLength !== undefined) parts.push(`length ${f.minLength ?? 0}..${f.maxLength ?? "*"}`);
  if (f.patterns && f.patterns.length === 1 && f.patterns[0].length === 1 && f.patterns[0][0].length < 80) parts.push(`pattern \`${f.patterns[0][0]}\``);
  return parts.length ? parts.join(", ") : undefined;
}

export function emitModule(ir: SchemaIR, runtimeImport: string): { code: string; stats: Record<string, number> } {
  const out: string[] = [];
  out.push(`// GENERATED by s1-codegen from ${ir.pl}. Do not edit.`);
  out.push(`import type { CT, ST } from ${lit(runtimeImport)};\n`);

  // ---------- simple type descriptors (deduplicated) ----------
  const stNames = new Map<string, string>();
  const stDecls: string[] = [];
  let anon = 0;
  const stExpr = (s: SimpleIR): string => {
    const f = s.facets;
    const o: string[] = [`b: ${lit(s.builtin)}`];
    if (f.patterns) o.push(`p: ${JSON.stringify(f.patterns)}`);
    if (f.enumeration) o.push(`e: ${JSON.stringify(f.enumeration)}`);
    if (f.length !== undefined) o.push(`l: ${f.length}`);
    if (f.minLength !== undefined) o.push(`mn: ${f.minLength}`);
    if (f.maxLength !== undefined) o.push(`mx: ${f.maxLength}`);
    if (f.totalDigits !== undefined) o.push(`td: ${f.totalDigits}`);
    if (f.fractionDigits !== undefined) o.push(`fd: ${f.fractionDigits}`);
    if (f.minInclusive !== undefined) o.push(`mi: ${lit(f.minInclusive)}`);
    if (f.maxInclusive !== undefined) o.push(`ma: ${lit(f.maxInclusive)}`);
    const nm = s.name ?? s.chain[0];
    if (nm) o.push(`nm: ${lit(nm)}`);
    return `{ ${o.join(", ")} }`;
  };
  const stRef = (s: SimpleIR): string => {
    const expr = stExpr(s);
    const found = stNames.get(expr);
    if (found) return found;
    const name = s.name ? `st_${ident(s.name)}` : `st$${anon++}`;
    stNames.set(expr, name);
    stDecls.push(`const ${name}: ST = ${expr};`);
    return name;
  };

  // ---------- TS value types ----------
  const typeDecls: string[] = [];
  const namedSimpleEmitted = new Set<string>();
  const valueType = (s: SimpleIR): string => {
    if (s.facets.enumeration) {
      const u = s.facets.enumeration.map(lit).join(" | ");
      if (s.name) {
        if (!namedSimpleEmitted.has(s.name)) {
          namedSimpleEmitted.add(s.name);
          typeDecls.push(jsdoc([s.doc, facetSummary(s)], "") + `export type ${ident(s.name)} = ${u};\n`);
        }
        return ident(s.name);
      }
      return u;
    }
    return "string";
  };
  const refType = (t: TypeRef): string => ("ref" in t ? ident(t.ref) : valueType(t));

  // fields of a particle: returns object members + union terms, for intersection
  type Shape = { members: string[]; unions: string[]; names: string[] };
  const shapeOf = (p: ParticleIR, forceOptional: boolean, forceArray: boolean, owner: string): Shape => {
    if (p.k === "el") {
      const arr = forceArray || p.max > 1;
      const opt = forceOptional || p.min === 0;
      const t = refType(p.type);
      const ty = arr ? (t.includes("|") ? `(${t})[]` : `${t}[]`) : t;
      const card = arr ? `occurs ${p.min}..${p.max === Infinity ? "n" : p.max}` : undefined;
      const doc = jsdoc([p.doc, !("ref" in p.type) ? facetSummary(p.type) : undefined, card], "  ");
      return { members: [`${doc}  ${propKey(p.name)}${opt ? "?" : ""}: ${ty};`], unions: [], names: [p.name] };
    }
    const rep = p.max > 1;
    if (p.k === "seq") {
      const parts = p.items.map((i) => shapeOf(i, forceOptional || p.min === 0, forceArray || rep, owner));
      const members = parts.flatMap((x) => x.members);
      const unions = parts.flatMap((x) => x.unions);
      const names = parts.flatMap((x) => x.names);
      return { members, unions, names };
    }
    // choice
    if (rep || forceArray) {
      // repeating choice: no exclusivity at type level (none in NF-e 4.00; kept as fallback)
      const parts = p.items.map((i) => shapeOf(i, true, true, owner));
      return { members: parts.flatMap((x) => x.members), unions: parts.flatMap((x) => x.unions), names: parts.flatMap((x) => x.names) };
    }
    const branches = p.items.map((i) => shapeOf(i, false, false, owner));
    const all = [...new Set(branches.flatMap((b) => b.names))];
    const term = (b: Shape) => {
      const nevers = all.filter((n) => !b.names.includes(n)).map((n) => `${propKey(n)}?: never`);
      const obj = `{\n${b.members.join("\n")}${nevers.length ? `\n  ${nevers.join("; ")};` : ""}\n}`;
      return [obj, ...b.unions.map((u) => `(${u})`)].join(" & ");
    };
    const terms = branches.map(term);
    if (p.min === 0 || forceOptional) terms.push(`{ ${all.map((n) => `${propKey(n)}?: never`).join("; ")} }`);
    return { members: [], unions: [terms.map((t) => `(${t})`).join("\n  | ")], names: all };
  };

  // ---------- complex: descriptors in dependency order ----------
  const ctDecls: string[] = [];
  const done = new Set<string>();
  const visiting = new Set<string>();
  let cycles = 0;
  const ctRef = (id: string): string => {
    if (!done.has(id)) emitComplex(ir.complex[id]);
    return ident(id);
  };
  const particleExpr = (p: ParticleIR, ownerNs: string): string => {
    const occ = (min: number, max: number) => `${min !== 1 ? `, n: ${min}` : ""}${max !== 1 ? `, x: ${max === Infinity ? -1 : max}` : ""}`;
    if (p.k === "el") {
      const t = "ref" in p.type ? ctRef(p.type.ref) : stRef(p.type);
      return `{ e: ${lit(p.name)}, t: ${t}${occ(p.min, p.max)}${p.ns !== ownerNs ? `, ns: ${lit(p.ns)}` : ""} }`;
    }
    return `{ g: ${lit(p.k === "seq" ? "s" : "c")}, i: [${p.items.map((i) => particleExpr(i, ownerNs)).join(", ")}]${occ(p.min, p.max)} }`;
  };
  const attrExpr = (a: AttrIR) => `{ a: ${lit(a.name)}, t: ${stRef(a.type)}${a.required ? ", r: 1" : ""}${a.fixed !== undefined ? `, f: ${lit(a.fixed)}` : ""} }`;

  function emitComplex(c: ComplexIR) {
    if (done.has(c.id)) return;
    if (visiting.has(c.id)) { cycles++; return; }
    visiting.add(c.id);
    const body: string[] = [`id: ${lit(c.id)}`, `ns: ${lit(c.ns)}`];
    if (c.attrs.length) body.push(`a: [${c.attrs.map(attrExpr).join(", ")}]`);
    if (c.content) body.push(`c: ${particleExpr(c.content, c.ns)}`);
    if (c.text) body.push(`tx: ${stRef(c.text)}`);
    visiting.delete(c.id);
    done.add(c.id);
    const name = ident(c.id);
    ctDecls.push(`export const ${name}: CT<${name}> = { ${body.join(", ")} };`);

    // TS type
    const members: string[] = [];
    for (const a of c.attrs) {
      const t = a.fixed !== undefined ? lit(a.fixed) : valueType(a.type);
      members.push(`${jsdoc([a.doc, `@attribute ${facetSummary(a.type) ?? ""}`], "  ")}  ${propKey(a.name)}${a.required ? "" : "?"}: ${t};`);
    }
    if (c.text) members.push(`  $text: string;`);
    let unions: string[] = [];
    if (c.content) {
      const sh = shapeOf(c.content, false, false, c.id);
      members.push(...sh.members);
      unions = sh.unions;
    }
    const obj = `{\n${members.join("\n")}\n}`;
    const def = [obj, ...unions.map((u) => `(\n  ${u}\n)`)].join(" & ");
    typeDecls.push(jsdoc([c.doc, `xsd: ${c.anonymous ? "anonymous type of " : ""}${c.id}`], "") + `export type ${name} = ${def};\n`);
  }

  for (const id of Object.keys(ir.complex)) emitComplex(ir.complex[id]);

  out.push("// ---------- types ----------\n");
  out.push(...typeDecls);
  out.push("\n// ---------- simple type descriptors ----------");
  out.push(...stDecls);
  out.push("\n// ---------- complex type descriptors (XSD order) ----------");
  out.push(...ctDecls);
  out.push(`\nexport const root = { name: ${lit(ir.root.name)}, ns: ${lit(ir.root.ns)}, type: ${ident(ir.root.type)} } as const;`);
  const code = out.join("\n") + "\n";
  return { code, stats: { complexTypes: done.size, simpleDescriptors: stDecls.length, cycles, bytes: code.length } };
}
